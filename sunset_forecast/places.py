def city_key(name: str) -> str:
    text = name.strip()
    for suffix in ("特别行政区", "地区", "自治州", "市", "县", "区", "盟"):
        if text.endswith(suffix) and len(text) > len(suffix):
            return text[: -len(suffix)]
    return text


def geocode_query_variants(location: str) -> list[str]:
    """Open-Meteo：广州能搜到，肇庆要肇庆市。两种都试。"""
    name = location.strip()
    variants = [name]
    key = city_key(name)
    if key and key not in variants:
        variants.append(key)
    city_form = key + "市" if key else name
    if city_form not in variants:
        variants.append(city_form)
    return variants
